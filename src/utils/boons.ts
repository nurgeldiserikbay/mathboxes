/**
 * Где открывается развилка.
 *
 * Сначала на десятом этаже, потом каждые тридцать: 10, 40, 70, 100.
 *
 * Раз в десять этажей выбор приходил слишком часто — он перестаёт быть
 * решением и становится диалогом, который закрывают не читая. Но и просто
 * «каждые тридцать» не годится: партии в этой игре в основном заканчиваются
 * около двадцатого этажа, и тогда большинство игроков не увидело бы механику
 * ни разу. Поэтому первая развилка стоит рано — чтобы с ней познакомились, —
 * а дальше редко, чтобы каждая следующая что-то значила.
 */
export const FORK_FIRST = 10
export const FORK_STEP = 30

/** Открывается ли развилка на этом этаже. */
export function isForkFloor(floor: number): boolean {
	if (floor < FORK_FIRST) return false
	return (floor - FORK_FIRST) % FORK_STEP === 0
}

