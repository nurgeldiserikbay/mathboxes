import { TYPE_BOON } from '@/utils/types'

/**
 * Развилка на опоре.
 *
 * До неё в игре не было ни одного решения — только исполнение: каждый ход это
 * «какое из чисел верное», и через десять этажей игрок уже видел всё, что игра
 * у него когда-либо спросит. Развилка добавляет то, чего не хватало: на каждой
 * опоре он выбирает, КАК строить следующий отрезок, и платит за выгоду
 * неудобством.
 *
 * Опора выбрана местом для этого не случайно: это единственная точка подъёма,
 * которая и так ощущается вехой — построенное закреплено, терять нечего, самое
 * время решать.
 *
 * Каждая дверь опирается на систему, которая в игре уже есть, и ничего нового
 * не изобретает: шаг опор, щит этажей и множитель очков.
 */
export interface I_Boon {
	kind: TYPE_BOON
	/** i18n-ключи имени и того, что дверь делает. */
	name: string
	note: string
	/** Имя иконки из `assets/icons`. */
	icon: string
	/** Сплошной акцент двери; из него выводятся все её оттенки. */
	tint: string
}

