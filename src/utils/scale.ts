/**
 * Масштаб интерфейса под крупный экран.
 *
 * Игра свёрстана в пикселях под телефон, и до сих пор на планшете это выходило
 * так: ширина тянулась, высота — нет. Блоки считаются долей от ширины сцены и
 * на десятидюймовом планшете разъезжались в полосы 204×58, высота этажа упёрта
 * в 58px и не росла вовсе, а вокруг колонки в 680px оставались тёмные поля в
 * треть экрана. Получался телефон, растянутый по одной оси.
 *
 * Чинить это можно было двумя способами: пересчитать каждый размер в вёрстке
 * или масштабировать всё целиком. Второй честнее — игра не становится другой на
 * планшете, она становится больше, как и должна казуальная аркада.
 *
 * Отсюда `zoom` на `#app`. Он, в отличие от `transform: scale`, меняет
 * собственную систему координат элемента: вёрстка внутри продолжает считать
 * себя телефоном шириной 440px, а на экран выводится крупно. Из этого следуют
 * два удобства и одна оговорка.
 *
 * Удобство первое: геометрия доски пересчитывается сама. `ResizeObserver`
 * отдаёт размер сцены до масштаба, так что `ClimbPage` видит привычные ~420×750
 * и раскладывает блоки ровно как на телефоне.
 *
 * Удобство второе: ввод не ломается. `columnAt` работает с долей от ширины
 * сцены, а не с пикселями, и доля от масштаба не зависит.
 *
 * Оговорка: вьюпортные единицы внутри `zoom` не сжимаются — `100dvh` останется
 * высотой экрана и после умножения даст страницу вдвое выше него. Поэтому
 * вместо `100dvh` в вёрстке стоит `--vh`, а рекламная полоса, наоборот,
 * заранее поделена на масштаб: её высоту диктует нативный баннер в физических
 * пикселях, и расти вместе с интерфейсом она не должна.
 */

/**
 * Экран, на котором масштаб равен единице.
 *
 * Ширина взята с запасом от самого широкого телефона (428px у крупных
 * «максов»), чтобы ни один телефон не получил дробный масштаб: там всё и так
 * выглядит правильно, а трогать то, что работает, перед выкладкой незачем.
 */
const DESIGN_WIDTH = 440
const DESIGN_HEIGHT = 800

/**
 * Докуда растём.
 *
 * Дальше расти нечему: при большем масштабе на экране остаётся меньше четырёх
 * этажей, и игроку становится не видно, куда прыгать.
 */
const MAX_SCALE = 2.6

function measure(width: number, height: number): number {
	const fit = Math.min(width / DESIGN_WIDTH, height / DESIGN_HEIGHT)
	// Меньше единицы не бывает: на маленьком экране вёрстка уже умеет ужиматься
	// сама, а `zoom` ниже единицы сделал бы подписи нечитаемыми.
	return Math.min(MAX_SCALE, Math.max(1, fit))
}

/**
 * Ширина и высота, по которым считали в прошлый раз.
 *
 * Нужны из-за экранной клавиатуры. Она ужимает окно по высоте — в настройках
 * есть поле имени, — и пересчёт на каждый `resize` менял бы масштаб всего
 * интерфейса прямо во время ввода. Поэтому высота учитывается только когда
 * растёт: клавиатура её отнимает, а вернуть больше, чем было, не может.
 */
let lastWidth = 0
let tallest = 0

export function applyScale(): void {
	if (window.innerWidth !== lastWidth) {
		lastWidth = window.innerWidth
		tallest = 0
	}
	tallest = Math.max(tallest, window.innerHeight)

	// Округление до сотых: лишние знаки дают субпиксельные швы между блоком и
	// его «губой», и на башне это видно как рябь по кромкам.
	const scale = Math.round(measure(lastWidth, tallest) * 100) / 100
	document.documentElement.style.setProperty('--k', String(scale))
}

/** Ставит масштаб и держит его при смене размера окна. */
export function watchScale(): void {
	applyScale()
	window.addEventListener('resize', applyScale)
}
